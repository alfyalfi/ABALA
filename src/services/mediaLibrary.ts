export function getRealPhoto(keyword: string): string | undefined {
  const clean = keyword.toLowerCase().trim();
  for (const [key, url] of Object.entries(REAL_PHOTOS)) {
    if (clean.includes(key)) return url;
  }
  return undefined;
}

export function getRealSound(keyword: string): string | undefined {
  const clean = keyword.toLowerCase().trim();
  for (const [key, url] of Object.entries(REAL_SOUNDS)) {
    if (clean.includes(key.split('_')[0])) return url;
  }
  return undefined;
}
